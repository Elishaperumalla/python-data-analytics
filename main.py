# E-COMMERCE SALES ANALYSIS
# Dataset: Approximately 500 records and 11 columns

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

# 1. LOAD THE DATASET
# The index_col parameter can be used to set a specific column
# as the DataFrame index.
# Example:
# data = pd.read_excel("sales_dataset.xlsx", index_col="Order_ID")

data = pd.read_excel("sales_dataset.xlsx")
# Display the loaded data
# print(data)

# Convert the loaded data into a Pandas DataFrame
df = pd.DataFrame(data)
# print(df)

# 2. UNDERSTANDING THE DATA

# Display basic information about the dataset
print(df.info())

# Display statistical summary of numerical columns
print(df.describe())

# Returns the number of rows and columns
print(df.shape)

# Display the first five rows
print(df.head())

# Display the last five rows
print(df.tail())

# Display all column names
print(df.columns)

# Display the frequency of unique row combinations
# print(df.value_counts())


# 3. DATA CLEANING

# Check for missing values in each column
print(df.isnull().sum())


# Check for duplicate rows
print("Duplicates:", df.duplicated().sum())


# Remove duplicate rows from the dataset
df = df.drop_duplicates()


# Convert the Order_Date column into Pandas datetime format
df["Order_Date"] = pd.to_datetime(df["Order_Date"])


# Check the data types of all columns
print(df.dtypes)


# 4. TOTAL REVENUE
# Calculate the total revenue generated from all sales
total_revenue = df["Sales"].sum()

print("Total Revenue:", total_revenue)


# 5. TOTAL ORDERS

# Count the number of unique orders.
# nunique() is used because one order can potentially contain
# multiple products or multiple rows in the dataset.

total_orders = df["Order_ID"].nunique()

print(f"Total Orders: {total_orders}")


# 6. AVERAGE ORDER VALUE (AOV)
# Calculate the average amount of revenue generated per order.
# Business meaning:
# AOV tells us how much money the company makes, on average,
# from one customer order.

average_order_value = total_revenue / total_orders

print(f"Average Order Value: {average_order_value}")


# 7. MONTHLY REVENUE TREND
# Create a new Month column from the Order_Date column.
# The "M" period represents the month.

df["Month"] = df["Order_Date"].dt.to_period("M")


# .dt provides access to datetime properties and functions.
# .to_period("M") converts each date into a monthly period.
# Example:
# 2024-05-15 -> 2024-05
# 2024-05-30 -> 2024-05 
# This is useful when grouping and aggregating sales
# month-wise without considering the exact day.
# Common frequency strings used with to_period():
# "M" -> Month
# "Q" -> Quarter
# "Y" -> Year
# "D" -> Day


# Group sales by month and calculate total sales for each month.
monthly_sales = df.groupby("Month")["Sales"].sum()

print(monthly_sales)


# -------------------- Monthly Sales Visualization --------------------

# Create a line chart to visualize monthly revenue trends.
monthly_sales.plot(kind="line", marker="o")

plt.title("Monthly Revenue Trend")
plt.xlabel("Month")
plt.ylabel("Revenue")
# Rotate x-axis labels by 45 degrees to improve readability.
plt.xticks(rotation=45)
# Automatically adjust the layout to prevent overlapping elements.
plt.tight_layout()
# Display the chart.
plt.show()


# 8. TOP 10 PRODUCTS BY SALES

# Group sales by Product.
# Calculate total sales for each product.
# Sort products from highest sales to lowest sales.
# Select the top 10 products.

top_products = (df.groupby("Product")["Sales"].sum().sort_values(ascending=False).head(10))


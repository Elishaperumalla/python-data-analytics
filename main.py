# 12. HIGHEST SALES MONTH
# idxmax() returns the index/label where the maximum value occurs.

highest_month = monthly_sales.idxmax()

# max() returns the highest sales value.
highest_sales = monthly_sales.max()

print(f"Highest Sales Month: {highest_month}")
print(f"Highest Sales: {highest_sales}")


# 13. LOWEST SALES MONTH
# idxmin() returns the index/label where the minimum value occurs.

lowest_month = monthly_sales.idxmin()

# min() returns the lowest sales value.
lowest_sales = monthly_sales.min()

print(f"Lowest Sales Month: {lowest_month}")
print(f"Lowest Sales: {lowest_sales}")


# 14. DISCOUNT VS SALES CORRELATION

# Calculate the correlation between Discount and Sales.
# Correlation shows the strength and direction of the
# relationship between two numerical variables.
# The value generally ranges from -1 to +1:
# +1  -> Strong positive relationship
#  0  -> No linear relationship
# -1  -> Strong negative relationship

correlation = df["Discount"].corr(df["Sales"])

print(f"Discount-Sales Correlation: {correlation}")


# Create a scatter plot to visually analyze the relationship
# between discount percentage/value and sales.

plt.scatter(df["Discount"], df["Sales"])

plt.title("Discount vs Sales")
plt.xlabel("Discount")
plt.ylabel("Sales")

plt.show()


# 15. NUMPY STATISTICAL ANALYSIS
# Select the Sales column for numerical/statistical analysis.
sales = df["Sales"]
# Mean represents the average sales value.
mean_sales = np.mean(sales)
# Median represents the middle value when all sales values
# are arranged in ascending order.

median_sales = np.median(sales)

# Standard deviation measures how much the sales values
# vary or spread around the mean.

std_sales = np.std(sales)

# 16. PERCENTILE ANALYSIS

# Percentiles divide the dataset into different percentage levels.
#
# Q25 -> 25% of sales values are below this value.
# Q50 -> 50% of sales values are below this value.
# Q75 -> 75% of sales values are below this value.

q25 = np.percentile(sales, 25)
q50 = np.percentile(sales, 50)
q75 = np.percentile(sales, 75)


# Display statistical results

print(f"Mean: {mean_sales}")
print(f"Median: {median_sales}")
print(f"Standard Deviation: {std_sales}")
print(f"25th Percentile: {q25}")
print(f"50th Percentile: {q50}")
print(f"75th Percentile: {q75}")


# 17. OUTLIER ANALYSIS USING IQR METHOD

# IQR stands for Interquartile Range.
# The IQR method is used to identify outliers in the dataset.
# An outlier is a data value that is significantly different
# from the majority of observations.
# Outlier analysis helps identify:
# - Unusually high transactions
# - Unusually low transactions
# - Possible data entry errors
# - Exceptional business transactions
# IQR represents the spread of the middle 50% of the data.

IQR = q75 - q25


# Calculate the lower boundary for identifying outliers.
# Values below this boundary are considered potential
# lower-side outliers.

lower_bouund = q25 - 1.5 * IQR


# Calculate the upper boundary for identifying outliers.
# Values above this boundary are considered potential
# upper-side outliers.

upper_bound = q75 + 1.5 * IQR


# Identify rows where Sales are outside the calculated boundaries.
# "|" represents OR.
# Therefore:
# Sales < Lower Bound
# OR
# Sales > Upper Bound
# These records are treated as potential outliers.

outliers = df[(sales < lower_bouund) | (sales > upper_bound)]

# Display the IQR boundaries and number of detected outliers.

print(f"Lower Bound: {lower_bouund}")
print(f"Upper Bound: {upper_bound}")
print(f"Number of Outliers: {len(outliers)}")